MONTHLY_DCA_CREATE_SQL = """
-- C-6/C-11 step 3 (2026-11-26). Confirmed monthly DCA plans and execution records, per owner, account scope
-- and KST month (YYYY-MM). Both tables are insert-only audit tables (no update/delete policy):
-- a confirmed plan is never overwritten; re-confirming adds plan_version + 1 and the latest version is active.
-- An execution record is unique per exec_key (scope|month|ticker|date|signal), so the same signal on the same
-- day cannot be recorded twice. The app writes with the service role; RLS limits any other client to its owner.
create table if not exists monthly_dca_plans (
  id bigint generated by default as identity primary key,
  owner_email text not null,
  account_scope text not null,
  account_label text not null default '',
  month_key text not null check (month_key ~ '^[0-9]{4}-[0-9]{2}$'),
  ticker text not null,
  holding_type text not null,
  plan_version integer not null default 1 check (plan_version >= 1),
  plan_krw numeric not null check (plan_krw >= 0),
  multiplier numeric,
  decision_code text,
  signal_label text,
  policy_version text not null,
  confirmed_at timestamptz not null default now(),
  unique (owner_email, account_scope, month_key, ticker, plan_version)
);

create table if not exists monthly_dca_executions (
  id bigint generated by default as identity primary key,
  owner_email text not null,
  account_scope text not null,
  month_key text not null check (month_key ~ '^[0-9]{4}-[0-9]{2}$'),
  ticker text not null,
  exec_date date not null,
  amount_krw numeric not null check (amount_krw > 0),
  plan_version integer,
  exec_key text not null,
  conditions jsonb not null default '{}'::jsonb,
  policy_version text not null,
  created_at timestamptz not null default now(),
  unique (owner_email, exec_key)
);

create index if not exists monthly_dca_plans_owner_idx on monthly_dca_plans(owner_email, account_scope, month_key);
create index if not exists monthly_dca_executions_owner_idx on monthly_dca_executions(owner_email, account_scope, month_key);

alter table monthly_dca_plans enable row level security;
alter table monthly_dca_executions enable row level security;

drop policy if exists monthly_dca_plans_owner_select on monthly_dca_plans;
drop policy if exists monthly_dca_plans_owner_insert on monthly_dca_plans;
drop policy if exists monthly_dca_executions_owner_select on monthly_dca_executions;
drop policy if exists monthly_dca_executions_owner_insert on monthly_dca_executions;

create policy monthly_dca_plans_owner_select on monthly_dca_plans for select
using (owner_email = coalesce(auth.jwt() ->> 'email', ''));
create policy monthly_dca_plans_owner_insert on monthly_dca_plans for insert
with check (owner_email = coalesce(auth.jwt() ->> 'email', ''));
create policy monthly_dca_executions_owner_select on monthly_dca_executions for select
using (owner_email = coalesce(auth.jwt() ->> 'email', ''));
create policy monthly_dca_executions_owner_insert on monthly_dca_executions for insert
with check (owner_email = coalesce(auth.jwt() ->> 'email', ''));
"""


